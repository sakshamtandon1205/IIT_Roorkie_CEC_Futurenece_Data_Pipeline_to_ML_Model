"""
Answers the six business questions from the ETL tables and from the ELT marts, side by side,
and writes the result to docs/business_questions.md (SQL and result for each pipeline).

    python include/tools/answers.py

Read-only on the warehouse. Only masked personal data is printed.
"""
from pathlib import Path

import duckdb
import pandas as pd

INCLUDE = Path(__file__).resolve().parents[1]
DB = INCLUDE / "warehouse_saksham.duckdb"
OUT = INCLUDE.parent / "docs" / "business_questions.md"

ETL_RUN = "(SELECT run_id FROM pipeline_runs WHERE dag_id = 'nammamart_etl_saksham' ORDER BY start_time DESC LIMIT 1)"
ELT_RUN = "(SELECT run_id FROM pipeline_runs WHERE dag_id = 'nammamart_elt_saksham' ORDER BY start_time DESC LIMIT 1)"

# (title, ETL sql, ELT sql, rows to show, sort columns for the comparison)
QUESTIONS = [
    ("1. Daily net revenue by zone and by store (delivered orders only, after discount)",
     "SELECT order_date, zone, store_id, delivered_orders, net_revenue FROM etl_daily_zone_revenue ORDER BY order_date, zone, store_id",
     "SELECT order_date, zone, store_id, delivered_orders, net_revenue FROM mart_daily_store_kpis ORDER BY order_date, zone, store_id",
     12),
    ("2. Revenue and gross margin by product category",
     "SELECT category, revenue, gross_margin, margin_pct FROM etl_category_margin ORDER BY revenue DESC",
     "SELECT category, revenue, gross_margin, margin_pct FROM mart_category_margin ORDER BY revenue DESC",
     20),
    ("3. Average delivery time per store, and % of delivered orders within 15 minutes",
     "SELECT store_id, store_name, avg_delivery_minutes, delivered_orders, pct_within_15_min FROM etl_store_delivery_sla ORDER BY store_id",
     "SELECT store_id, store_name, avg_delivery_minutes, delivered_orders, pct_within_15_min FROM mart_delivery_sla ORDER BY store_id",
     20),
    ("4a. Revenue by payment mode",
     "SELECT payment_mode, revenue, delivered_orders FROM etl_revenue_by_payment_mode ORDER BY revenue DESC",
     "SELECT payment_mode, revenue, delivered_orders FROM mart_revenue_by_payment_mode ORDER BY revenue DESC",
     10),
    ("4b. Amount that does not reconcile with the payment gateway",
     "SELECT COUNT(*) AS mismatches, ROUND(SUM(ABS(difference)), 2) AS amount_not_reconciling FROM etl_payment_reconciliation",
     "SELECT COUNT(*) AS mismatches, ROUND(SUM(ABS(difference)), 2) AS amount_not_reconciling FROM mart_payment_reconciliation",
     10),
    ("5. Top 10 customers by spend, with loyalty tier (masked)",
     "SELECT customer_id, customer_name_masked, loyalty_tier, total_spend, delivered_orders FROM etl_top_customers ORDER BY total_spend DESC, customer_id",
     "SELECT customer_id, customer_name_masked, loyalty_tier, total_spend, delivered_orders FROM mart_top_customers ORDER BY total_spend DESC, customer_id",
     10),
    ("6. Rows rejected in the latest run, by file and reason",
     f"SELECT file, failure_reason, COUNT(*) AS rows FROM etl_quarantine_log WHERE run_id = {ETL_RUN} GROUP BY 1, 2 ORDER BY 1, 3 DESC, 2",
     f"SELECT file, failure_reason, COUNT(*) AS rows FROM elt_rejected_rows WHERE _run_id = {ELT_RUN} GROUP BY 1, 2 ORDER BY 1, 3 DESC, 2",
     60),
]


def md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    rows = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        rows.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |")
    return "\n".join(rows)


def main():
    con = duckdb.connect(str(DB), read_only=True)
    lines = ["# Business questions answered by both pipelines", "",
             "Each question is one query on the ETL tables and one on the ELT marts. "
             "Generated by `python include/tools/answers.py` from the warehouse after the final clean run of both DAGs.", ""]
    for title, etl_sql, elt_sql, show in QUESTIONS:
        etl = con.execute(etl_sql).df()
        elt = con.execute(elt_sql).df()
        same = etl.reset_index(drop=True).equals(elt.reset_index(drop=True)) or \
            etl.round(2).reset_index(drop=True).equals(elt.round(2).reset_index(drop=True))
        verdict = f"identical ({len(etl)} rows)" if same else f"different (ETL {len(etl)} rows, ELT {len(elt)} rows)"
        lines += [f"## {title}", "", f"Comparison of the full ETL and ELT results: **{verdict}**.", "",
                  "ETL query:", "```sql", etl_sql.strip(), "```", "",
                  "ELT query:", "```sql", elt_sql.strip(), "```", "",
                  f"ELT result{' (first %d rows)' % show if len(elt) > show else ''}:", "", md(elt.head(show)), ""]
        if not same:
            lines += [f"ETL result{' (first %d rows)' % show if len(etl) > show else ''}:", "", md(etl.head(show)), ""]
        print(f"{title}: {verdict}")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"\nwrote {OUT}")


if __name__ == "__main__":
    main()
