-- SQL-only staging step. Rows are never dropped here: rows that broke a Critical check
--  stay in the table with dq_status = 'QUARANTINED' and the reasons in failure_reason.

CREATE OR REPLACE TABLE stg_orders AS
SELECT TRIM(order_id) AS order_id, ts_val AS order_ts, CAST(ts_val AS DATE) AS order_date,
       TRIM(customer_id) AS customer_id, TRIM(store_id) AS store_id, TRIM(product_id) AS product_id,
       CAST(qty AS BIGINT) AS quantity, price AS unit_price, disc AS discount_pct, ROUND(amt, 2) AS order_amount,
       pay_std AS payment_mode, status_u AS order_status, TRIM(channel) AS channel, mins AS delivery_minutes,
       CASE WHEN CONCAT_WS('; ',
        CASE WHEN c_customer_id_not_null THEN 'customer_id_not_null' END,
        CASE WHEN c_order_ts_not_null THEN 'order_ts_not_null' END,
        CASE WHEN c_delivered_has_delivery_minutes THEN 'delivered_has_delivery_minutes' END,
        CASE WHEN c_order_id_unique THEN 'order_id_unique' END,
        CASE WHEN c_order_status_allowed THEN 'order_status_allowed' END,
        CASE WHEN c_payment_mode_known THEN 'payment_mode_known' END,
        CASE WHEN c_discount_pct_between_0_and_100 THEN 'discount_pct_between_0_and_100' END,
        CASE WHEN c_order_ts_parses THEN 'order_ts_parses' END,
        CASE WHEN c_quantity_positive THEN 'quantity_positive' END,
        CASE WHEN c_order_amount_matches_formula THEN 'order_amount_matches_formula' END,
        CASE WHEN c_delivery_minutes_at_most_120 THEN 'delivery_minutes_at_most_120' END,
        CASE WHEN c_delivery_minutes_positive THEN 'delivery_minutes_positive' END,
        CASE WHEN c_customer_exists_in_customers THEN 'customer_exists_in_customers' END,
        CASE WHEN c_product_exists_in_products THEN 'product_exists_in_products' END,
        CASE WHEN c_store_exists_in_stores THEN 'store_exists_in_stores' END,
        CASE WHEN c_order_ts_not_in_future THEN 'order_ts_not_in_future' END) = '' THEN 'PASSED' ELSE 'QUARANTINED' END AS dq_status,
       CONCAT_WS('; ',
        CASE WHEN c_customer_id_not_null THEN 'customer_id_not_null' END,
        CASE WHEN c_order_ts_not_null THEN 'order_ts_not_null' END,
        CASE WHEN c_delivered_has_delivery_minutes THEN 'delivered_has_delivery_minutes' END,
        CASE WHEN c_order_id_unique THEN 'order_id_unique' END,
        CASE WHEN c_order_status_allowed THEN 'order_status_allowed' END,
        CASE WHEN c_payment_mode_known THEN 'payment_mode_known' END,
        CASE WHEN c_discount_pct_between_0_and_100 THEN 'discount_pct_between_0_and_100' END,
        CASE WHEN c_order_ts_parses THEN 'order_ts_parses' END,
        CASE WHEN c_quantity_positive THEN 'quantity_positive' END,
        CASE WHEN c_order_amount_matches_formula THEN 'order_amount_matches_formula' END,
        CASE WHEN c_delivery_minutes_at_most_120 THEN 'delivery_minutes_at_most_120' END,
        CASE WHEN c_delivery_minutes_positive THEN 'delivery_minutes_positive' END,
        CASE WHEN c_customer_exists_in_customers THEN 'customer_exists_in_customers' END,
        CASE WHEN c_product_exists_in_products THEN 'product_exists_in_products' END,
        CASE WHEN c_store_exists_in_stores THEN 'store_exists_in_stores' END,
        CASE WHEN c_order_ts_not_in_future THEN 'order_ts_not_in_future' END) AS failure_reason,
       _source_file, _run_id, _row_num, _loaded_at
FROM chk_orders
WHERE _source_file = 'orders.csv';
